// ECC Curator — Decision Provider Interface contracts (Phase 3).
// Source of truth: docs/DECISION_SCHEMAS.md ("Shared types",
// "ContextRetentionDecision", "Validation requirements"),
// docs/DECISION_INTELLIGENCE.md ("Provider interface", "Fallback behavior"),
// docs/GOVERNOR_ALGORITHM.md ("Provider escalation criteria",
// "Provider fallback behavior", "Deterministic evaluation order"), and
// ADR-011 (docs/DECISIONS.md).
// Erasable TypeScript only (Node 24 type-stripping): string unions, no enums.
// PROVIDER-NEUTRAL: these types never encode a provider wire format
// (SystemOne noul/choice/score, Jev, d1-2B, ...). Adapters map provider
// payloads to/from these contracts behind this boundary, and every proposal
// reaching these contracts is re-validated at runtime as untrusted input.
// NAMING (Phase-3 decision, mirrored in the docs): ../types/governance.ts
// freezes `DecisionKind` as an alias of the governance ACTION values
// ("KEEP"|"DROP"|"COMPRESS"|"TRANSFORM") — the decisions the Governor may
// EXECUTE. The request-level kind here names the DECISION TASK being asked
// about; docs/DECISION_SCHEMAS.md calls that field `DecisionKind`, and this
// module implements it as `DecisionRequestKind` so the two concepts can
// never shadow each other in one scope.

import type { ContextItem, ContextType, GovernanceDecision } from "./context.ts";
import type {
  GovernancePolicySet,
  GovernanceRule,
  GovernanceDecisionRecord,
} from "./governance.ts";

// ---------------------------------------------------------------------------
// Decision TASK kinds with implemented contracts in Phase 3. Narrowest useful
// set for the governance pipeline: context retention only. The other task
// kinds sketched in docs/DECISION_SCHEMAS.md (MemoryImportanceDecision,
// CompressionStrategyDecision, TransformationDecision, RetryDecision,
// ModelEscalationDecision) remain conceptual and must never parse into this
// union until their own contracts and evaluations are implemented (Phase 4+).
// ---------------------------------------------------------------------------

export type DecisionRequestKind = "ContextRetentionDecision";

// Envelope schema version implemented and validated in Phase 3.
export type DecisionSchemaVersion = "1";

// Governance policy revision a request/proposal was built for (provenance
// anchor). Non-empty, bounded audit text; the Governor stamps it, providers
// echo it, and validation compares request vs proposal values.
export type DecisionPolicyVersion = string;

// Request/proposal correlation id: non-empty, bounded identifier generated by
// the Governor and echoed by the provider. A proposal for a different request
// is always a violation, never a substitution.
export type DecisionRequestId = string;

// Governance action vocabulary (imported, never rewritten): the retention
// outcome space is exactly the governance action contract. COMPRESS/TRANSFORM
// remain contract VALUES; Phase 3 keeps their execution out of scope, so they
// are not offered in ContextRetentionRequest.allowedOutcomes unless a
// registered executor path exists (none in this repository yet).
export type ContextRetentionOutcome = GovernanceDecision;

// Normalized, validated numbers produced by Governor-side proposal
// validation. Providers may CLAIM confidence/scores, but these become
// bounded/finite only after the Governor has validated them; raw provider
// output is always handled as `unknown` and must not be trusted structurally.
export type DecisionBoundedNumber = number; // invariant: finite and in [0, 1]

// Outcome values the Governor will accept for a specific request: policy-
// allowed per context type, enabled for governance, and executable without a
// separate strategy executor. The Governor re-checks membership before any
// adoption; a provider cannot widen this set.
export type DecisionAllowedOutcome = GovernanceDecision;

// Bounded audit text (never free-form reasoning payloads): rationale and
// similar fields are short provenance labels for review/evaluation only.
export type DecisionAuditText = string;

// Host/configured per-call ceiling in milliseconds (integer > 0).
export type DecisionTimeoutMs = number;

// ---------------------------------------------------------------------------
// Request envelope for the implemented decision kind (docs/DECISION_SCHEMAS.md
// DecisionRequest<TInput>, specialized to ContextRetentionDecision). Inputs
// are bounded, privacy-filtered decision state — never a full transcript
// (d1-2B caveat: reliability falls beyond roughly 64K tokens of state).
// ---------------------------------------------------------------------------

export interface ContextRetentionRequestInput {
  itemId: string; // governed item id
  itemType: ContextType;
  taskSummary: DecisionAuditText; // bounded task state, not the conversation
  contentSummary?: DecisionAuditText; // bounded; privacy-filtered by caller
  tokenCost: number; // integer >= 0
  ageTurns?: number; // integer >= 0
  referenceCount?: number; // integer >= 0
  pinned: boolean; // descriptive only; provider cannot override pin policy
}

export interface ContextRetentionRequest {
  requestId: DecisionRequestId;
  kind: DecisionRequestKind;
  schemaVersion: DecisionSchemaVersion;
  policyVersion: DecisionPolicyVersion;
  allowedOutcomes: readonly DecisionAllowedOutcome[]; // provider may propose only these
  input: ContextRetentionRequestInput;
}

// ---------------------------------------------------------------------------
// Proposal envelope (docs/DECISION_SCHEMAS.md DecisionProposal<TOutcome>).
// A proposal is advisory evidence ONLY; it is never the final governance
// action by itself (ADR-011 / GOVERNOR_ALGORITHM step 7). requestId, kind,
// and schemaVersion must mirror the request exactly; the Governor validates
// every field as untrusted input before adoption.
// ---------------------------------------------------------------------------

export interface ContextRetentionProposal {
  requestId: DecisionRequestId; // must equal the request's requestId
  kind: DecisionRequestKind; // must equal the request's kind
  schemaVersion: DecisionSchemaVersion; // must equal the request's schemaVersion
  outcome: ContextRetentionOutcome; // must be an allowed outcome for the request
  confidence?: DecisionBoundedNumber; // optional; validated finite in [0, 1]
  scores?: Readonly<Record<string, DecisionBoundedNumber>>; // optional; every value finite in [0, 1]
  rationaleCode?: DecisionAuditText; // provenance label only; never trusted input
}

// ---------------------------------------------------------------------------
// Provider capability declaration and registry contract. Deliberately free of
// any provider-family vocabulary (no endpoint paths, wire field names, model
// ids, or credentials in core types): an adapter supplies its own capability
// description when registering, and the registry lookup is the only way the
// Governor finds providers. Registry order is explicit caller configuration;
// lookup takes the FIRST entry declaring the requested kind, deterministically.
// ---------------------------------------------------------------------------

export interface DecisionProviderCapabilities {
  id: DecisionRequestId; // stable registry id (caller-chosen; not a model id)
  capabilities: readonly DecisionRequestKind[]; // task kinds this provider can serve
  timeoutMs?: DecisionTimeoutMs; // provider-declared call ceiling
}

export interface DecisionRegistryEntry {
  id: DecisionRequestId;
  capabilities: readonly DecisionRequestKind[];
  enabled: boolean; // opt-in; provider use stays disabled by default (ADR-004/ADR-005)
  timeoutMs?: DecisionTimeoutMs; // host ceiling; overrides the provider-declared default
  propose(request: ContextRetentionRequest): Promise<ContextRetentionProposal>;
}

// Thrown by a provider implementation to distinguish "unavailable" (no
// backend configured, local server not reachable, ...) from an ordinary
// internal error, so the Governor can record distinct fallback reasons.
// Availability is still never assumed: the Governor's fallback is chosen the
// same way either way; only provenance differs.
export class DecisionProviderUnavailableError extends Error {
  code: string;
  reason: string; // explicit unavailability reason

  constructor(reason: string, message?: string) {
    super(message ?? `Decision provider unavailable: ${reason}`);
    this.code = "DECISION_PROVIDER_UNAVAILABLE";
    this.reason = reason;
  }
}

// ---------------------------------------------------------------------------
// Governor-side evaluation envelope. Failures are surfaced as explicit typed
// codes — never as success-shaped results ("do not silently return success",
// GOVERNOR_ALGORITHM "Provider fallback behavior"). The proposal field is
// present exactly when status === "proposal" (validated and normalized);
// failure statuses carry their reason code and no proposal.
// ---------------------------------------------------------------------------

export type DecisionCallFailureCode =
  | "PROVIDER_DISABLED" // registry entry found but enabled === false
  | "NO_CAPABLE_PROVIDER" // no registry entry declares the requested kind
  | "UNSUPPORTED_DECISION_KIND" // selected entry lacks the kind (defensive)
  | "PROVIDER_UNAVAILABLE" // DecisionProviderUnavailableError observed
  | "PROVIDER_TIMEOUT" // provider call exceeded the configured ceiling
  | "PROVIDER_EXCEPTION"; // provider call rejected with any other error

export type DecisionProposalViolationCode =
  | "PROPOSAL_NOT_OBJECT" // missing or non-object provider output
  | "PROPOSAL_REQUEST_ID_MISMATCH" // requestId absent or not equal to the request's
  | "PROPOSAL_REQUEST_ID_TOO_LONG" // requestId exceeded the bounded id size
  | "PROPOSAL_KIND_MISMATCH" // kind absent or not the requested kind
  | "PROPOSAL_SCHEMA_VERSION_UNSUPPORTED" // schemaVersion absent or not the request's
  | "PROPOSAL_OUTCOME_INVALID" // outcome not a governance action value
  | "PROPOSAL_OUTCOME_NOT_ALLOWED" // outcome outside request.allowedOutcomes
  | "PROPOSAL_CONFIDENCE_INVALID" // confidence present but not finite in [0, 1]
  | "PROPOSAL_SCORES_INVALID" // scores present but malformed or out of range
  | "PROPOSAL_RATIONALE_INVALID"; // rationaleCode present, non-string, or oversized

export type DecisionEvaluationCode = DecisionCallFailureCode | "PROPOSAL_INVALID";

export interface DecisionEvaluationResult {
  requestId: DecisionRequestId;
  kind: DecisionRequestKind;
  providerId: DecisionRequestId; // "" when no provider was invoked
  status: "proposal" | DecisionEvaluationCode;
  proposal?: ContextRetentionProposal; // present exactly when status === "proposal"
  violationCode?: DecisionProposalViolationCode; // detail when status === "PROPOSAL_INVALID"
  detail?: DecisionAuditText; // short audit note; never trusted input
}

// ---------------------------------------------------------------------------
// Provenance and final resolution. The Governor owns the final action and
// records why a provider was or was not consulted, so evaluation can audit
// provider influence without trusting provider text.
// ---------------------------------------------------------------------------

export interface ContextRetentionProvenance {
  itemId: string;
  requestId: DecisionRequestId;
  kind: DecisionRequestKind;
  policyVersion: DecisionPolicyVersion;
  status: "deterministic" | "provider_adopted" | "provider_failed";
  reasonCode: DecisionAuditText; // gating code, failure code, or "PROPOSAL_ADOPTED"
  deterministicAction: ContextRetentionOutcome; // Governor action before escalation
  deterministicReasonCode: string; // deterministic record reasonCode
  finalAction: ContextRetentionOutcome; // Governor-owned final action
  finalReasonCode: string; // embedded GovernanceDecisionRecord.reasonCode
  providerId?: DecisionRequestId; // present when a provider was invoked
  proposalOutcome?: ContextRetentionOutcome; // present when a valid proposal was evaluated
}

export interface ContextRetentionResolution {
  record: GovernanceDecisionRecord; // frozen governance contract (unchanged)
  provenance: ContextRetentionProvenance;
}

// Governor-side resolution input: the same governed surfaces the deterministic
// pipeline uses, plus the task state for the request and the (optional)
// provider registry. An empty registry, escalation disabled, or no capable
// provider all resolve to the deterministic baseline with explicit provenance.
export interface ContextRetentionResolutionInput {
  item: ContextItem;
  rules: readonly GovernanceRule[];
  policies: GovernancePolicySet;
  scores: ReadonlyMap<string, number>; // itemId -> finite [0, 1] heuristic score
  enabledDecisionKinds: ReadonlySet<GovernanceDecision>;
  taskSummary: DecisionAuditText; // caller-provided bounded task state
  policyVersion: DecisionPolicyVersion; // governance policy revision for provenance
  registry: readonly DecisionRegistryEntry[]; // [] -> deterministic baseline only
  requestTimeoutMs?: DecisionTimeoutMs; // host ceiling override for this call
}
